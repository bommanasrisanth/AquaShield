export function isRTL(lang: LanguageCode): boolean {
  return lang === 'ar';
}

export function detectBrowserLanguage(): LanguageCode {
  if (typeof navigator === 'undefined') return 'en';
  const navLang = (navigator.language || (navigator as any).userLanguage || 'en').toLowerCase();
  if (navLang.startsWith('hi')) return 'hi';
  if (navLang.startsWith('te')) return 'te';
  if (navLang.startsWith('ta')) return 'ta';
  if (navLang.startsWith('ne')) return 'ne';
  if (navLang.startsWith('bn')) return 'bn';
  if (navLang.startsWith('es')) return 'es';
  if (navLang.startsWith('fr')) return 'fr';
  if (navLang.startsWith('ar')) return 'ar';
  if (navLang.startsWith('pt')) return 'pt';
  if (navLang.startsWith('id')) return 'id';
  if (navLang.startsWith('sw')) return 'sw';
  return 'en';
}

export function getSpokenAlertText(status: FloodStatusLevel, lang: LanguageCode): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  switch (status) {
    case 'SAFE':
      return dict.spokenSafe;
    case 'WATCH':
      return dict.spokenWatch;
    case 'PREPARE':
      return dict.spokenPrepare;
    case 'LEAVE NOW':
      return dict.spokenLeaveNow;
    default:
      return dict.spokenSafe;
  }
}
